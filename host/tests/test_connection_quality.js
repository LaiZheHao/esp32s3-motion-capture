"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm");
const source=fs.readFileSync(require("node:path").join(__dirname,"../web/app.js"),"utf8");
const elements=new Map();
const context={$:id=>{if(!elements.has(id))elements.set(id,{textContent:"",firstChild:{textContent:""}});return elements.get(id);},format:value=>Number(value).toFixed(2)};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf("function renderBodyLoss("),source.indexOf("window.renderBodyDiagnostic=")),context);
const quality={sequence:50000,valid_frames:4,missing_frames:40995,connection:{has_samples:true,valid_frames:1,missing_frames:0,loss_percent:0}};
const original=JSON.stringify(quality);
context.renderBodyLoss({},quality,false);
assert.equal(elements.get("loss").textContent,"0.00%");assert.match(elements.get("lossLabel").firstChild.textContent,/本次连接/);
context.renderBodyLoss({}, {...quality,connection:{has_samples:true,loss_percent:25}},false);
assert.equal(elements.get("loss").textContent,"25.00%");
context.renderBodyLoss({},quality,true);assert.match(elements.get("lossLabel").firstChild.textContent,/记录时/);
context.renderBodyLoss({}, {...quality,connection:{has_samples:false,loss_percent:null}},false);assert.equal(elements.get("loss").textContent,"—");
context.renderBodyLoss({}, {sequence:0,valid_frames:3,missing_frames:1},true);
assert.equal(elements.get("loss").textContent,"25.00%");assert.match(elements.get("lossLabel").firstChild.textContent,/累计/);
context.renderBodyLoss({}, {valid_frames:3,missing_frames:0},false);assert.equal(elements.get("loss").textContent,"—");
assert.equal(JSON.stringify(quality),original);
context.renderBodyLoss(null,{},false);assert.equal(elements.get("loss").textContent,"—");assert.match(elements.get("lossLabel").firstChild.textContent,/本次连接/);
console.log("Loss display: current connection excludes lifetime gaps; real gaps, replay, old recordings and unknown sequence preserved");
